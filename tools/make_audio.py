def kick(dur=0.22):
    return tone(freq_curve(150, 45, dur), dur, "sine", attack=0.001, decay=5.0)


def snare(dur=0.16, seed=2):
    body = tone(freq_curve(260, 180, dur), dur, "triangle", attack=0.001, decay=8.0) * 0.4
    return body + bandpass(noise(dur, seed), 2400, 0.9) * env_ad(dur, 0.001, 7.0) * 0.9


def hat(dur=0.05, seed=3):
    return highpass(noise(dur, seed), 7000) * env_ad(dur, 0.0005, 6.0)


CHORDS = {
    "C": (60, 64, 67), "Dm": (62, 65, 69), "Em": (64, 67, 71), "F": (65, 69, 72), "G": (67, 71, 74),
    "Am": (69, 72, 76), "Bb": (70, 74, 77), "D": (62, 66, 69), "Bm": (71, 74, 78), "A": (69, 73, 76),
}


def render_song(bpm: float, progression: list[str], scale: list[int], seed: int, lead_shape: str,
                swing: float = 0.0, transpose: int = 0) -> np.ndarray:
    """A small original chiptune loop: bass, arpeggio, lead melody and drums.
    The melody is composed by a seeded random walk over chord tones, with the
    first phrase repeated (varied) later so it sounds like a tune."""
    rng = np.random.default_rng(seed)
    beat = 60.0 / bpm
    bar = beat * 4
    total = bar * len(progression)
    tail = 1.5
    buf = np.zeros(n_of(total + tail))

    def put(start: float, sound: np.ndarray, gain: float) -> None:
        i = n_of(start) if start > 0 else 0
        j = min(len(buf), i + len(sound))
        buf[i:j] += sound[: j - i] * gain

    def sw(step_time: float, sixteenth: int) -> float:
        return step_time + (swing * beat * 0.25 if sixteenth % 2 == 1 else 0.0)

    # Melody phrases, 2 bars each; phrase 0 comes back as phrase 2 (varied).
    rhythms = [
        [1, 0.5, 0.5, 1, 1],
        [0.5, 0.5, 1, 0.5, 0.5, 1],
        [1.5, 0.5, 1, 1],
        [0.5, 0.5, 0.5, 0.5, 2],
        [1, 1, 0.5, 0.5, 1],
    ]
    phrases: list[list[tuple[float, float, int]]] = []
    prev = 72 + transpose
    for p in range(len(progression) // 2):
        if p % 4 == 2 and phrases:
            base = phrases[p - 2]
            varied = [(b, d, m + (2 if i == len(base) - 1 else 0)) for i, (b, d, m) in enumerate(base)]
            phrases.append(varied)
            continue
        notes = []
        for half in range(2):
            chord = [c + transpose for c in CHORDS[progression[p * 2 + half]]]
            pattern = rhythms[rng.integers(len(rhythms))]
            pos = 0.0
            for k, d in enumerate(pattern):
                strong = abs(pos - round(pos)) < 1e-6 and int(round(pos)) % 2 == 0
                if strong or rng.random() < 0.5:
                    cand = [c + 12 for c in chord] + chord
                else:
                    cand = [72 + transpose + s for s in scale] + [60 + transpose + s for s in scale]
                cand = [c for c in cand if 64 + transpose <= c <= 86 + transpose]
                cand.sort(key=lambda c: abs(c - prev) + rng.random() * 3.0)
                m = cand[0] if rng.random() < 0.7 else cand[min(1, len(cand) - 1)]
                if p == len(progression) // 2 - 1 and half == 1 and k == len(pattern) - 1:
                    m = 72 + transpose  # resolve home
                notes.append((half * 4 + pos, d, m))
                prev = m
                pos += d
        phrases.append(notes)

    for bar_i, name in enumerate(progression):
        t0 = bar_i * bar
        chord = [c + transpose for c in CHORDS[name]]
        root = chord[0] - 24
        # Bass: oom-pah with a walk-up on the last eighth.
        for b in range(4):
            m = root if b % 2 == 0 else root + 7
            put(t0 + b * beat, tone(midi_hz(m), beat * 0.9, "triangle", attack=0.004, decay=2.2), 0.42)
        put(t0 + 3.5 * beat, tone(midi_hz(root + 12), beat * 0.45, "triangle", attack=0.004, decay=3.0), 0.25)
        # Arpeggio in sixteenths.
        arp = chord + [chord[0] + 12]
        for s in range(16):
            m = arp[[0, 1, 2, 3, 2, 1][s % 6]] + 12
            put(sw(t0 + s * beat * 0.25, s), tone(midi_hz(m), beat * 0.24, "square", duty=0.125, attack=0.002,
                                                 decay=5.0), 0.05)
        # Drums.
        for b in range(4):
            if b in (0, 2):
                put(t0 + b * beat, kick(), 0.5)
            if b in (1, 3):
                put(t0 + b * beat, snare(), 0.22)
            for e in range(2):
                put(sw(t0 + b * beat + e * beat * 0.5, e * 2), hat(), 0.08 if e == 0 else 0.05)
        if bar_i % 4 == 3:
            put(t0 + 3.5 * beat, snare(0.12, 5), 0.16)
            put(t0 + 3.75 * beat, snare(0.12, 6), 0.18)

    # Lead melody.
    for p, notes in enumerate(phrases):
        base_t = p * 2 * bar
        for b, d, m in notes:
            dur = d * beat * 0.92
            x = osc(midi_hz(m), dur, lead_shape, duty=0.25, vibrato=0.006, vib_rate=5.5)
            x *= env_adsr(dur, 0.01, 0.08, 0.7, min(0.08, dur * 0.4))
            put(base_t + b * beat, lowpass(x, 4500), 0.2)

    # Seamless loop: add the reverb, then fold everything that rings past the
    # loop end (note tails and reverb) back onto the start.
    loop_n = n_of(total)
    wet = room(buf, 0.12)
    out = np.zeros(loop_n)
    for start in range(0, len(wet), loop_n):
        chunk = wet[start:start + loop_n]
        out[: len(chunk)] += chunk
    out = np.tanh(out * 1.4) / np.tanh(1.4)
    out -= np.mean(out)
    return out / np.max(np.abs(out)) * 0.6


MAJOR_PENTA = [0, 2, 4, 7, 9]


def music_menu():
    prog = ["C", "Am", "F", "G", "C", "Am", "F", "G", "F", "G", "Em", "Am", "F", "G", "C", "C"]
