#!/usr/bin/env python3
"""Synthesizes every sound effect and music loop in assets/audio/.

All audio in The Chaos Switch is generated by this script from simple
waveforms and noise: no samples, no recordings and no third-party sound
packs, so it is original and free to use, change and redistribute with the
game. Re-run it after changing a sound:

    python tools/make_audio.py              # everything
    python tools/make_audio.py jump star    # only some sounds

Needs Python 3.9+ with numpy and scipy (pip install numpy scipy).
If ffmpeg is installed, the two music loops are also converted to Ogg Vorbis
(much smaller); otherwise they stay as .wav files. The game's AudioManager
picks up res://assets/audio/<id>.ogg or <id>.wav automatically.

Every sound id here matches a hook in the game code, for example
AudioManager.play(&"jump"). See assets/audio/README.md for the list.
"""

