def write_wav(path: str, x: np.ndarray) -> None:
    data = np.clip(x, -1.0, 1.0)
    pcm = (data * 32767.0).astype("<i2")
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())


def main(argv: list[str]) -> int:
    os.makedirs(OUT_DIR, exist_ok=True)
    wanted = set(argv)
    made = 0
    for name, fn in SFX.items():
        if wanted and name not in wanted:
            continue
        x = fn()
        write_wav(os.path.join(OUT_DIR, name + ".wav"), x)
        made += 1
        print(f"{name:16s} {len(x) / SR:5.2f}s")
    ffmpeg = shutil.which("ffmpeg")
    for name, fn in MUSIC.items():
        if wanted and name not in wanted:
            continue
        x = fn()
        wav_path = os.path.join(OUT_DIR, name + ".wav")
        write_wav(wav_path, x)
        made += 1
        if ffmpeg:
            ogg_path = os.path.join(OUT_DIR, name + ".ogg")
            subprocess.run([ffmpeg, "-y", "-loglevel", "error", "-i", wav_path, "-c:a", "libvorbis", "-q:a", "4",
                            ogg_path], check=True)
            os.remove(wav_path)
            print(f"{name:16s} {len(x) / SR:5.2f}s  -> ogg")
        else:
            print(f"{name:16s} {len(x) / SR:5.2f}s  (wav; install ffmpeg for a smaller .ogg)")
    print(f"Made {made} sound(s) in {os.path.normpath(OUT_DIR)}")
    return 0


