# --------------------------------------------------------------------------- basics

def n_of(dur: float) -> int:
    return max(1, int(round(dur * SR)))


def tl(dur: float) -> np.ndarray:
    return np.arange(n_of(dur)) / SR


def freq_curve(f0: float, f1: float, dur: float, curve: str = "exp") -> np.ndarray:
    x = np.linspace(0.0, 1.0, n_of(dur))
    if curve == "exp" and f0 > 0 and f1 > 0:
        return f0 * (f1 / f0) ** x
    if curve == "ease":
        x = 1.0 - (1.0 - x) ** 2
    return f0 + (f1 - f0) * x


def _blep(ph: np.ndarray, dt: np.ndarray) -> np.ndarray:
    out = np.zeros_like(ph)
    m = ph < dt
    x = ph[m] / dt[m]
    out[m] = x + x - x * x - 1.0
    m2 = ph > 1.0 - dt
    x = (ph[m2] - 1.0) / dt[m2]
    out[m2] = x * x + x + x + 1.0
    return out


def osc(freq, dur: float, shape: str = "sine", duty: float = 0.5, vibrato: float = 0.0,
        vib_rate: float = 6.0, phase: float = 0.0) -> np.ndarray:
    """Band-limited oscillator. [freq] is a number or a per-sample array."""
    n = n_of(dur)
    f = np.full(n, float(freq)) if np.ndim(freq) == 0 else np.resize(np.asarray(freq, float), n)
    if vibrato > 0.0:
        f = f * (1.0 + vibrato * np.sin(2 * np.pi * vib_rate * np.arange(n) / SR))
    dt = np.clip(f / SR, 1e-6, 0.49)
    ph = (np.cumsum(dt) + phase) % 1.0
    if shape == "sine":
        return np.sin(2 * np.pi * ph)
    if shape == "triangle":
        return 1.0 - 4.0 * np.abs(ph - 0.5)
    if shape == "saw":
        return 2.0 * ph - 1.0 - _blep(ph, dt)
    if shape == "square":
        sq = np.where(ph < duty, 1.0, -1.0)
        return sq + _blep(ph, dt) - _blep((ph + 1.0 - duty) % 1.0, dt)
    raise ValueError(shape)


def noise(dur: float, seed: int = 1) -> np.ndarray:
    return np.random.default_rng(seed).uniform(-1.0, 1.0, n_of(dur))


def env_ad(dur: float, attack: float = 0.005, decay_shape: float = 4.0) -> np.ndarray:
    """Quick attack, exponential-ish decay to silence at the end."""
    n = n_of(dur)
    t = np.arange(n) / SR
    a = np.clip(t / max(attack, 1e-4), 0.0, 1.0)
    d = np.exp(-decay_shape * t / dur)
    d = (d - d[-1]) / max(1e-9, (d[0] - d[-1]))
    return a * d


def env_adsr(dur: float, a: float, d: float, s: float, r: float) -> np.ndarray:
    n = n_of(dur)
    t = np.arange(n) / SR
    e = np.ones(n) * s
    e[t < a] = t[t < a] / max(a, 1e-4)
    m = (t >= a) & (t < a + d)
    e[m] = 1.0 - (1.0 - s) * (t[m] - a) / max(d, 1e-4)
    rel = t > dur - r
    e[rel] *= np.clip((dur - t[rel]) / max(r, 1e-4), 0.0, 1.0)
    return e


def lowpass(x: np.ndarray, cutoff: float, order: int = 2) -> np.ndarray:
    b, a = signal.butter(order, min(cutoff, SR * 0.45) / (SR / 2), "low")
    return signal.lfilter(b, a, x)


def highpass(x: np.ndarray, cutoff: float, order: int = 2) -> np.ndarray:
    b, a = signal.butter(order, cutoff / (SR / 2), "high")
    return signal.lfilter(b, a, x)


def bandpass(x: np.ndarray, center: float, q: float = 4.0) -> np.ndarray:
    b, a = signal.iirpeak(min(center, SR * 0.45), q, SR)
    return signal.lfilter(b, a, x)


def pad(x: np.ndarray, dur: float) -> np.ndarray:
    n = n_of(dur)
    return np.pad(x, (0, max(0, n - len(x))))[:max(n, len(x))]


def mix(*sounds: np.ndarray) -> np.ndarray:
    """Adds sounds of different lengths (all starting at time 0)."""
    out = np.zeros(max(len(s) for s in sounds))
    for s in sounds:
        out[: len(s)] += s
    return out


def at(total: float, parts: list[tuple[float, np.ndarray]]) -> np.ndarray:
    """Mixes (start_time, sound) parts into one buffer of [total] seconds."""
    out = np.zeros(n_of(total))
    for start, s in parts:
        i = n_of(start) if start > 0 else 0
        j = min(len(out), i + len(s))
        if j > i:
            out[i:j] += s[: j - i]
    return out


def tone(freq, dur: float, shape: str = "triangle", attack: float = 0.004, decay: float = 4.0,
         **kw) -> np.ndarray:
    return osc(freq, dur, shape, **kw) * env_ad(dur, attack, decay)


def bell(freq: float, dur: float, bright: float = 0.5) -> np.ndarray:
    """A small toy glockenspiel note."""
    x = osc(freq, dur, "sine") + bright * 0.4 * osc(freq * 2.76, dur, "sine") * env_ad(dur, 0.002, 9.0)
    x += bright * 0.18 * osc(freq * 5.4, dur, "sine") * env_ad(dur, 0.001, 16.0)
    return x * env_ad(dur, 0.002, 5.0)


def room(x: np.ndarray, mix: float = 0.18, size: float = 1.0) -> np.ndarray:
    """A tiny, cheap reverb (a few feedback combs + one allpass)."""
    out = np.copy(x)
    wet = np.zeros(len(x) + n_of(0.5 * size))
    src = np.pad(x, (0, len(wet) - len(x)))
    for delay, fb in ((0.0297, 0.62), (0.0371, 0.58), (0.0411, 0.55), (0.0437, 0.52)):
        d = n_of(delay * size)
        b = np.zeros(d + 1)
        b[0] = 1.0
        a = np.zeros(d + 1)
        a[0] = 1.0
        a[d] = -fb
        wet += signal.lfilter(b, a, src)
    d = n_of(0.005)
    b = np.zeros(d + 1)
    b[0] = -0.6
    b[d] = 1.0
    a = np.zeros(d + 1)
    a[0] = 1.0
    a[d] = -0.6
    wet = signal.lfilter(b, a, wet) * 0.25
    wet = lowpass(wet, 5000)
    out = np.pad(out, (0, len(wet) - len(out)))
    return out * (1.0 - mix * 0.5) + wet * mix


def finish(x: np.ndarray, peak: float = 0.7, fade_in: float = 0.002, fade_out: float = 0.012) -> np.ndarray:
    x = x - np.mean(x)
    fi = min(len(x), n_of(fade_in))
    fo = min(len(x), n_of(fade_out))
    x[:fi] *= np.linspace(0.0, 1.0, fi)
    x[len(x) - fo:] *= np.linspace(1.0, 0.0, fo)
    m = np.max(np.abs(x))
    if m > 0:
        x = x / m * peak
    # Trim trailing silence.
    nz = np.nonzero(np.abs(x) > 0.0008)[0]
    if len(nz):
        x = x[: min(len(x), nz[-1] + n_of(0.01))]
    return x


def note(name: str) -> float:
    """note("C5") -> Hz. Sharps as C#5."""
    names = {"C": 0, "C#": 1, "D": 2, "D#": 3, "E": 4, "F": 5, "F#": 6, "G": 7, "G#": 8, "A": 9, "A#": 10, "B": 11}
    key, octave = name[:-1], int(name[-1])
    midi = 12 * (octave + 1) + names[key]
    return midi_hz(midi)


def midi_hz(m: float) -> float:
    return 440.0 * 2.0 ** ((m - 69) / 12.0)


# --------------------------------------------------------------------------- voices

VOWELS = {
    "oo": (320, 800, 2240),
    "oh": (500, 880, 2400),
    "ah": (760, 1150, 2500),
    "uh": (600, 1050, 2350),
    "ee": (300, 2100, 2900),
    "eh": (530, 1750, 2500),
}


def vowel(source: np.ndarray, v: str) -> np.ndarray:
    f1, f2, f3 = VOWELS[v]
    return bandpass(source, f1, 5) * 1.0 + bandpass(source, f2, 7) * 0.6 + bandpass(source, f3, 9) * 0.25


def voice(contour: np.ndarray, vowels: tuple[str, str], dur: float, wobble: float = 0.02,
          wobble_rate: float = 7.0) -> np.ndarray:
    """A cartoon creature syllable: buzzy source through vowel formants,
    morphing from the first vowel to the second."""
    src = osc(contour, dur, "saw", vibrato=wobble, vib_rate=wobble_rate) * 0.6
    src += osc(contour, dur, "square", duty=0.3, vibrato=wobble, vib_rate=wobble_rate) * 0.25
    a = vowel(src, vowels[0])
    b = vowel(src, vowels[1])
    blend = np.linspace(0.0, 1.0, len(src)) ** 1.5
    out = a * (1.0 - blend) + b * blend
    # A pure tone underneath keeps it round and cute rather than buzzy.
    out = lowpass(out, 3200) + osc(contour, dur, "sine", vibrato=wobble, vib_rate=wobble_rate) * 0.35
    return out * env_adsr(dur, 0.02, 0.05, 0.85, 0.08)


